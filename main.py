def git_receive_pack(store, repo, body):
    """Parse push commands + pack; apply fast-forward-only ref updates.
    Returns the sideband report bytes."""
    packets, rest = pkt_lines(body)
    commands = []
    for kind, payload in packets:
        if kind != "data":
            continue
        line = payload.decode("utf-8", "replace")
        nul = line.find("\0")
        if nul >= 0:
            line = line[:nul]
        line = line.strip()
        if not line:
            continue
        parts = line.split(" ")
        if len(parts) >= 3:
            commands.append((parts[0], parts[1], parts[2]))
    out = bytearray()
    report = []
    if rest:
        try:
            objs = read_pack(rest)
        except Exception as exc:
            report.append("unpack %s\n" % exc)
            out += pkt(b"\x01" + pkt(("unpack %s\n" % exc).encode()))
            out += FLUSH
            return bytes(out)
        for oid, otype, data in objs:
            store.put(otype, data)
            if otype == "blob":
                STORE_BLOB_CACHE[oid] = data
    unpack_ok = True
    for old, new, ref in commands:
        cur = repo.refs.get(ref)
        if new == ZERO_OID:  # delete
            if cur is None:
                report.append("ng %s remote ref does not exist\n" % ref)
            else:
                del repo.refs[ref]
                report.append("ok %s\n" % ref)
        elif old == ZERO_OID:  # create
            if cur is not None:
                report.append("ng %s reference already exists\n" % ref)
            elif not store.has(new):
                report.append("ng %s object not found\n" % ref)
            else:
                repo.refs[ref] = new
                report.append("ok %s\n" % ref)
        else:  # update: must be fast-forward
            if cur is None:
                report.append("ng %s remote ref does not exist\n" % ref)
            elif cur != old:
                report.append("ng %s non-fast-forward\n" % ref)
            elif not store.has(new):
                report.append("ng %s object not found\n" % ref)
            elif not store.is_ancestor(old, new):
                report.append("ng %s non-fast-forward\n" % ref)
            else:
                repo.refs[ref] = new
                report.append("ok %s\n" % ref)
    out += pkt(b"\x01" + pkt(b"unpack ok\n"))
    for line in report:
        out += pkt(b"\x01" + pkt(line.encode()))
    out += FLUSH
    return bytes(out)

