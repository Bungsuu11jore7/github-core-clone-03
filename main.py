def _resolve_value(v, variables):
    if isinstance(v, dict):
        if "var" in v:
            return variables.get(v["var"])
        if "enum" in v:
            return v["enum"]
        return {k: _resolve_value(x, variables) for k, x in v.items()}
    if isinstance(v, list):
        return [_resolve_value(x, variables) for x in v]
    return v


