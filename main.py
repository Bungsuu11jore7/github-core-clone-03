def _mcp_owner_repo(args):
    owner = args.get("owner")
    repo = args.get("repo")
    full = args.get("full_name")
    if full and "/" in full:
        owner, repo = full.split("/", 1)
    if not repo:
        return None, None
    if not owner:
        owner = VIEWER_LOGIN
