def _json_body(raw):
    if not raw:
        return {}
    try:
        data = json.loads(raw.decode("utf-8"))
    except Exception:
        raise RestError(400, "Invalid JSON body")
    if not isinstance(data, dict):
        raise RestError(400, "Invalid JSON body")
    return data


def rest_dispatch(method, path, query, headers, raw, base_url=""):
    """Returns (status, body_obj_or_None, extra_headers). Raises RestError."""
    if method == "GET" and path == "/healthz":
        return 200, {"ok": True}, {}
    if not path.startswith("/api/v3"):
        raise RestError(404, "Not Found")
    # auth: every /api/v3 call needs the shop token
    token = headers.get("authorization", "")
    if SHOP_TOKEN:
        if token != "Bearer " + SHOP_TOKEN:
            raise RestError(401, "Requires authentication")
    sub = path[len("/api/v3"):]
    if sub == "" or sub == "/":
        if method != "GET":
            raise RestError(404, "Not Found")
        return 200, {"current_user_url": "/api/v3/user",
                     "repository_url": "/api/v3/repos/{owner}/{repo}",
                     "meta": "/api/v3/meta"}, {"X-OAuth-Scopes": "repo, read:org"}
    if sub == "/meta":
        if method != "GET":
            raise RestError(404, "Not Found")
        return 200, {"installed_version": "1.0.0"}, {}
    parts = [unquote(p) for p in sub.strip("/").split("/") if p != ""]
    body = _json_body(raw) if method in ("POST", "PUT", "PATCH", "DELETE") else {}
    return _rest_route(method, parts, query, body, headers, base_url)


def _rest_route(method, parts, query, body, headers, base_url=""):
    if parts == ["user", "repos"]:
        if method == "POST":
            name = body.get("name")
            if not name or not isinstance(name, str):
                raise RestError(422, "name is required")
            repo = STORE.create_repo(VIEWER_LOGIN, name, bool(body.get("private", False)),
                                     body.get("description", ""))
            if repo is None:
                raise RestError(422, "Repository already exists")
            return 201, repo_json(repo), {}
        if method == "GET":
            items = [repo_json(r) for r in STORE.list_repos(VIEWER_LOGIN)]
            chunk, link = paginate(items, query, base_url + "/api/v3/user/repos")
            extra = {"Link": link} if link else {}
            return 200, chunk, extra
        raise RestError(404, "Not Found")
    if len(parts) >= 3 and parts[0] == "repos":
        owner, name = parts[1], parts[2]
        rest = parts[3:]
        if not rest:
            repo = _need_repo(owner, name)
            if method == "GET":
                return 200, repo_json(repo), {}
            if method == "PATCH":
                if "description" in body:
                    repo.description = body["description"]
                if "default_branch" in body:
                    repo.default_branch = body["default_branch"]
                return 200, repo_json(repo), {}
            if method == "DELETE":
                STORE.delete_repo(owner, name)
                return 204, None, {}
            raise RestError(404, "Not Found")
        return _repo_sub(method, owner, name, rest, query, body)
    raise RestError(404, "Not Found")


def _repo_sub(method, owner, name, rest, query, body):
    repo = _need_repo(owner, name)
    if rest == ["branches"]:
        if method != "GET":
            raise RestError(404, "Not Found")
        out = [{"name": ref[len("refs/heads/"):], "commit": {"sha": oid}}
               for ref, oid in sorted(repo.refs.items())
               if ref.startswith("refs/heads/")]
        return 200, out, {}
    if rest == ["commits"]:
        if method != "GET":
            raise RestError(404, "Not Found")
        sha = query.get("sha", [None])[0]
        tip = STORE.resolve_ref(repo, sha) if sha else STORE.head_commit(repo)
        if tip is None:
            return 200, [], {}
        got = STORE.objects.get(tip)
        if got is None:
            raise RestError(404, "No commit found for SHA: %s" % sha)
        if got[0] == "tag":
            tip = parse_tag(got[1])["object"]
        chain = STORE.objects.commit_chain(tip)
        out = []
        for oid in reversed(chain):
            c = parse_commit(STORE.objects.get(oid)[1])
            out.append({"sha": oid, "commit": {"message": c["message"].rstrip("\n"),
                        "tree": {"sha": c["tree"]}},
                        "parents": [{"sha": p} for p in c["parents"]]})
        return 200, out, {}
    if rest == ["git", "refs"]:
        if method != "POST":
            raise RestError(404, "Not Found")
        ref = body.get("ref", "")
        sha = body.get("sha", "")
        if not ref.startswith("refs/") or not STORE.objects.get(sha):
            raise RestError(422, "Invalid ref or sha")
        if ref in repo.refs:
            raise RestError(422, "Reference already exists")
        repo.refs[ref] = sha
        return 201, {"ref": ref, "object": {"sha": sha, "type": "commit"}}, {}
    if rest[0] == "contents":
        return _contents(method, repo, rest[1:], query, body)
    if rest == ["labels"]:
        if method != "POST":
            raise RestError(404, "Not Found")
        lname = body.get("name")
        if not lname:
            raise RestError(422, "name is required")
        if lname in repo.labels:
            raise RestError(422, "Label already exists")
        repo.labels[lname] = body.get("color", "ffffff")
        return 201, {"name": lname, "color": repo.labels[lname]}, {}
    if rest[0] == "issues":
        return _issues(method, repo, rest[1:], query, body)
    if rest[0] == "pulls":
        return _pulls(method, repo, rest[1:], query, body)
    raise RestError(404, "Not Found")

def _contents(method, repo, rest, query, body):
    fpath = "/".join(rest)
    ref = query.get("ref", [None])[0]
    tip = STORE.resolve_ref(repo, ref) if ref else STORE.head_commit(repo)
    if method == "GET":
        if tip is None:
            raise RestError(404, "Not Found")
        got = STORE.objects.get(tip)
        if got is None:
            raise RestError(404, "Not Found")
        if got[0] == "tag":
            tip = parse_tag(got[1])["object"]
        tree_oid = parse_commit(STORE.objects.get(tip)[1])["tree"]
        files = tree_files(STORE.objects, tree_oid)
        if not fpath:
            entries = _dir_listing(repo, files, "")
            return 200, entries, {}
        if fpath in files:
            oid, _mode = files[fpath]
            data = STORE.objects.get(oid)[1]
            return 200, {"type": "file", "encoding": "base64", "size": len(data),
                         "name": fpath.split("/")[-1], "path": fpath, "sha": oid,
                         "content": base64.b64encode(data).decode()}, {}
        entries = _dir_listing(repo, files, fpath)
        if entries is None:
            raise RestError(404, "Not Found")
        return 200, entries, {}
    if method == "PUT":
        message = body.get("message", "")
        content_b64 = body.get("content", "")
        try:
            data = base64.b64decode(content_b64, validate=False)
        except Exception:
            raise RestError(422, "content must be base64")
        branch = body.get("branch") or repo.default_branch
        refname = "refs/heads/" + branch
        cur_tip = repo.refs.get(refname)
        if cur_tip is None and repo.refs:
            raise RestError(422, "No commit found for branch %s" % branch)
        files = {}
        parents = []
        if cur_tip is not None:
            got = STORE.objects.get(cur_tip)
            if got is None:
                raise RestError(422, "No commit found for branch %s" % branch)
            files = tree_files(STORE.objects, parse_commit(got[1])["tree"])
            parents = [cur_tip]
        existed = fpath in files
        if existed:
            if "sha" in body and body["sha"] != files[fpath][0]:
                raise RestError(409, "sha does not match")
        blob_oid = STORE.put_blob(data)
        files[fpath] = (blob_oid, "100644")
        tree_oid = build_tree_from_files(STORE.objects, files)
        ts = STORE.next_ts()
        author = "%s <%s>" % (VIEWER_NAME, VIEWER_EMAIL)
        cdata = build_commit(tree_oid, parents, message, author, author, ts)
        commit_oid = STORE.objects.put("commit", cdata)
        repo.refs[refname] = commit_oid
        status = 200 if existed else 201
        return status, {"content": {"name": fpath.split("/")[-1], "path": fpath,
                                    "sha": blob_oid, "size": len(data),
                                    "encoding": "base64"},
                        "commit": {"sha": commit_oid, "message": message}}, {}
    if method == "DELETE":
        message = body.get("message", "")
        branch = body.get("branch") or repo.default_branch
        refname = "refs/heads/" + branch
        cur_tip = repo.refs.get(refname)
        if cur_tip is None:
            raise RestError(404, "Not Found")
        files = tree_files(STORE.objects, parse_commit(STORE.objects.get(cur_tip)[1])["tree"])
        if fpath not in files:
            raise RestError(404, "Not Found")
        if "sha" in body and body["sha"] != files[fpath][0]:
            raise RestError(409, "sha does not match")
        del files[fpath]
        tree_oid = build_tree_from_files(STORE.objects, files)
        ts = STORE.next_ts()
        author = "%s <%s>" % (VIEWER_NAME, VIEWER_EMAIL)
        cdata = build_commit(tree_oid, [cur_tip], message, author, author, ts)
        commit_oid = STORE.objects.put("commit", cdata)
        repo.refs[refname] = commit_oid
        return 200, {"commit": {"sha": commit_oid, "message": message}}, {}
    raise RestError(404, "Not Found")


def _dir_listing(repo, files, prefix):
    """Entries directly under prefix ('' = root). None if prefix is not a dir."""
    entries, seen = {}, False
    for path, (oid, _mode) in files.items():
        if prefix and not path.startswith(prefix + "/"):
            continue
        rel = path[len(prefix) + 1:] if prefix else path
        head, _, _tail = rel.partition("/")
        if head == "":
            continue
        seen = True
        if _tail:
            entries[head] = {"type": "dir", "name": head,
                             "path": (prefix + "/" + head) if prefix else head,
                             "sha": None}
        else:
            entries[head] = {"type": "file", "name": head, "path": path,
                             "sha": oid, "size": len(STORE.objects.get(oid)[1])}
    if not seen and prefix:
        return None
    return [entries[k] for k in sorted(entries)]


def _issues(method, repo, rest, query, body):
    if not rest:
        if method == "POST":
            title = body.get("title")
            if not title:
                raise RestError(422, "title is required")
            issue, err = STORE.create_issue(repo, title, body.get("body", ""),
                                            body.get("labels", []))
            if issue is None:
                raise RestError(422, err)
            return 201, issue_json(repo, issue), {}
        if method == "GET":
            state = query.get("state", ["open"])[0]
            direction = query.get("direction", ["asc"])[0]
            items = [i for i in repo.issues.values()
                     if state == "all" or i["state"] == state]
            items.sort(key=lambda i: i["number"], reverse=(direction == "desc"))
            return 200, [issue_json(repo, i) for i in items], {}
        raise RestError(404, "Not Found")
    try:
        n = int(rest[0])
    except ValueError:
        raise RestError(404, "Not Found")
    issue = repo.issues.get(n)
    if issue is None:
        raise RestError(404, "Not Found")
    if len(rest) == 1:
        if method == "GET":
            return 200, issue_json(repo, issue), {}
        if method == "PATCH":
            if "state" in body:
                if body["state"] not in ("open", "closed"):
                    raise RestError(422, "invalid state")
                issue["state"] = body["state"]
            if "title" in body:
                issue["title"] = body["title"]
            if "body" in body:
                issue["body"] = body["body"]
            issue["updated_at"] = STORE.iso(STORE.next_ts())
            return 200, issue_json(repo, issue), {}
        raise RestError(404, "Not Found")
    if rest[1] == "comments":
        if method == "POST":
            cbody = body.get("body")
            if not cbody:
                raise RestError(422, "body is required")
            cid = repo.next_comment
            repo.next_comment += 1
            ts = STORE.next_ts()
            comment = {"id": cid, "body": cbody,
                       "created_at": STORE.iso(ts), "updated_at": STORE.iso(ts),
                       "user": {"login": VIEWER_LOGIN}}
            repo.comments[n].append(comment)
            return 201, comment, {}
        if method == "GET":
            return 200, list(repo.comments[n]), {}
        raise RestError(404, "Not Found")
    raise RestError(404, "Not Found")


def _pulls(method, repo, rest, query, body):
    if not rest:
        if method == "POST":
            title = body.get("title")
            head = body.get("head")
            base = body.get("base")
            if not title or not head or not base:
                raise RestError(422, "title, head and base are required")
            pr, err = STORE.create_pull(repo, title, head, base, body.get("body", ""))
            if pr is None:
                raise RestError(422, err)
            return 201, pr_json(STORE, repo, pr), {}
        if method == "GET":
            state = query.get("state", ["open"])[0]
            items = [p for p in repo.pulls.values()
                     if state == "all" or p["state"] == state]
            items.sort(key=lambda p: p["number"])
            return 200, [pr_json(STORE, repo, p) for p in items], {}
        raise RestError(404, "Not Found")
    try:
        n = int(rest[0])
    except ValueError:
        raise RestError(404, "Not Found")
    pr = repo.pulls.get(n)
    if pr is None:
        raise RestError(404, "Not Found")
    if len(rest) == 1:
        if method == "GET":
            return 200, pr_json(STORE, repo, pr), {}
        raise RestError(404, "Not Found")
    if rest[1] == "files":
        if method != "GET":
            raise RestError(404, "Not Found")
        base_oid = STORE.merge_base(repo, pr["head_sha"], pr["base_sha"])
        if base_oid is None:
            raise RestError(422, "No merge base")
        base_tree = tree_files(STORE.objects, parse_commit(STORE.objects.get(base_oid)[1])["tree"])
        head_tree = tree_files(STORE.objects, parse_commit(STORE.objects.get(pr["head_sha"])[1])["tree"])
        out = [{"filename": p, "status": s, "additions": a, "deletions": d,
                "changes": a + d}
               for p, s, a, d in diff_files(STORE.objects, base_tree, head_tree)]
        return 200, out, {}
    if rest[1] == "merge":
        if method != "PUT":
            raise RestError(404, "Not Found")
        sha, status, err = STORE.merge_pull(repo, pr)
        if status != 200:
            raise RestError(status, err)
        return 200, {"sha": sha, "merged": True,
                     "message": "Pull Request successfully merged"}, {}
    raise RestError(404, "Not Found")

# ---------------------------------------------------------------- GraphQL v4
_TOKEN_RE = re.compile(r'\s*(?:#.*?$|(\.\.\.)|([A-Za-z_][A-Za-z0-9_]*)|(\$[A-Za-z_][A-Za-z0-9_]*)|("(?:[^"\\]|\\.)*")|(-?\d+(?:\.\d+)?)|([{}()\[\]:!@=,|&]))', re.M | re.S)


def _gql_tokens(text):
    toks, i = [], 0
    while i < len(text):
        m = _TOKEN_RE.match(text, i)
        if not m or m.end() == i:
            raise ValueError("GraphQL parse error at %d" % i)
        i = m.end()
        if m.group(1):
            toks.append(("...", "..."))
        elif m.group(2):
            toks.append(("name", m.group(2)))
        elif m.group(3):
            toks.append(("var", m.group(3)[1:]))
        elif m.group(4):
            toks.append(("string", json.loads(m.group(4))))
        elif m.group(5):
            raw = m.group(5)
            toks.append(("number", float(raw) if "." in raw else int(raw)))
        elif m.group(6):
            toks.append((m.group(6), m.group(6)))
    toks.append(("eof", None))
    return toks


class _GqlParser:
    def __init__(self, text):
        self.toks = _gql_tokens(text)
        self.i = 0

    def peek(self):
        return self.toks[self.i]

    def next(self):
        t = self.toks[self.i]
        self.i += 1
        return t

    def expect(self, kind):
        t = self.next()
        if t[0] != kind:
            raise ValueError("expected %s, got %r" % (kind, t))
        return t[1]

    def expect_name(self):
        return self.expect("name")

    def parse_document(self):
        defs = []
        while self.peek()[0] != "eof":
            if self.peek() == ("{", "{"):
                defs.append({"kind": "operation", "op": "query", "name": None,
                             "vars": {}, "selection": self.parse_selection_set()})
            elif self.peek()[0] == "name" and self.peek()[1] in ("query", "mutation", "subscription"):
                op = self.next()[1]
                name = None
                if self.peek()[0] == "name":
                    name = self.next()[1]
                variables = {}
                if self.peek() == ("(", "("):
                    variables = self.parse_var_defs()
                defs.append({"kind": "operation", "op": op, "name": name,
                             "vars": variables, "selection": self.parse_selection_set()})
            elif self.peek() == ("name", "fragment"):
                self.next()
                name = self.expect_name()
                self.expect_name()  # "on"
                typename = self.expect_name()
                defs.append({"kind": "fragment", "name": name, "type": typename,
                             "selection": self.parse_selection_set()})
            else:
                raise ValueError("unexpected token %r" % (self.peek(),))
        return defs

    def parse_var_defs(self):
        variables = {}
        self.expect("(")
        while self.peek() != (")", ")"):
            if self.peek()[0] == "var":
                vname = self.next()[1]
                self.expect(":")
                self.parse_type()
                if self.peek() == ("=", "="):
                    self.next()
                    self.parse_value()
                variables[vname] = None
            else:
                self.next()
            if self.peek() == (",", ","):
                self.next()
        self.expect(")")
        return variables

    def parse_type(self):
        if self.peek() == ("[", "["):
            self.next()
            self.parse_type()
            self.expect("]")
        else:
            self.expect_name()
        if self.peek() == ("!", "!"):
            self.next()

    def parse_selection_set(self):
        self.expect("{")
        sels = []
        while self.peek() != ("}", "}"):
            sels.append(self.parse_selection())
        self.expect("}")
        return sels

    def parse_selection(self):
        if self.peek() == ("...", "..."):
            self.next()
            if self.peek()[0] == "name" and self.peek()[1] == "on":
                self.next()
                typename = self.expect_name()
                return {"fragment": "inline", "type": typename,
                        "selection": self.parse_selection_set()}
            if self.peek()[0] == "name":
                return {"fragment": self.next()[1]}
            return {"fragment": "inline", "type": None,
                    "selection": self.parse_selection_set()}
        name = self.expect_name()
        alias = None
        if self.peek() == (":", ":"):
            self.next()
            alias = name
            name = self.expect_name()
        args = {}
        if self.peek() == ("(", "("):
            self.next()
            while self.peek() != (")", ")"):
                aname = self.expect_name()
                self.expect(":")
                args[aname] = self.parse_value()
                if self.peek() == (",", ","):
                    self.next()
            self.expect(")")
        if self.peek() == ("@", "@"):
            self.next()
            self.expect_name()
            if self.peek() == ("(", "("):
                depth = 0
                while True:
                    t = self.next()
                    if t[0] == "(":
                        depth += 1
                    elif t[0] == ")":
                        depth -= 1
                        if depth == 0:
                            break
        selection = None
        if self.peek() == ("{", "{"):
            selection = self.parse_selection_set()
        return {"field": name, "alias": alias or name, "args": args,
                "selection": selection}

    def parse_value(self):
        t = self.peek()
        if t[0] == "var":
            self.next()
            return {"var": t[1]}
        if t[0] == "string":
            self.next()
            return t[1]
        if t[0] == "number":
            self.next()
            return t[1]
        if t[0] == "name":
            self.next()
            if t[1] == "true":
                return True
            if t[1] == "false":
                return False
            if t[1] == "null":
                return None
            return {"enum": t[1]}
        if t == ("[", "["):
            self.next()
            out = []
            while self.peek() != ("]", "]"):
                out.append(self.parse_value())
                if self.peek() == (",", ","):
                    self.next()
            self.expect("]")
            return out
        if t == ("{", "{"):
            self.next()
            out = {}
            while self.peek() != ("}", "}"):
                k = self.expect_name()
                self.expect(":")
                out[k] = self.parse_value()
                if self.peek() == (",", ","):
                    self.next()
            self.expect("}")
            return out
        raise ValueError("unexpected value token %r" % (t,))

