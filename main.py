def _cursor(pos):
    return _b64("c:%d" % pos)


def _uncursor(cursor):
    if not cursor:
        return -1
    try:
        text = _unb64(cursor)
        if text and text.startswith("c:"):
            return int(text[2:])
    except Exception:
        return -1
    return -1


def _connection(items, args):
    """items: list of parent objects (already ordered). Returns a
    connection parent object honoring first/after."""
    first = args.get("first")
    after = _uncursor(args.get("after"))
    start = after + 1
    page = items[start:start + first] if isinstance(first, int) else items[start:]
    end_cursor = _cursor(start + len(page) - 1) if page else None
    return {"__type": "Connection", "nodes": page,
            "edges": [{"__type": "Edge", "node": it, "cursor": _cursor(start + k)}
                      for k, it in enumerate(page)],
            "pageInfo": {"__type": "PageInfo",
                         "hasNextPage": start + len(page) < len(items),
                         "hasPreviousPage": start > 0,
                         "startCursor": _cursor(start) if page else None,
                         "endCursor": end_cursor},
            "totalCount": len(items)}


