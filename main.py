def _decode_global_id(gid):
    """Returns (kind, dbid, number) for Repository/Issue/PullRequest ids."""
    if not gid:
        return None
    text = _unb64(gid)
    if not text:
        return None
    parts = text.split(":")
    if len(parts) == 2 and parts[0] == "Repository":
        return ("Repository", int(parts[1]), None)
    if len(parts) == 3 and parts[0] in ("Issue", "PullRequest"):
        return (parts[0], int(parts[1]), int(parts[2]))
    if len(parts) == 2 and parts[0] == "User":
        return ("User", parts[1], None)
    return None

