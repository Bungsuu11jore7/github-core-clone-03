# ---------------------------------------------------------------- pkt-lines
def pkt(data):
    """Encode bytes as one pkt-line (data must end with \\n unless flush)."""
    return ("%04x" % (len(data) + 4)).encode() + data


FLUSH = b"0000"
DELIM = b"0001"


def pkt_lines(body):
    """Parse a byte buffer into (packets, rest): packets are ('data', bytes),
    ('flush', None), ('delim', None); rest is the unparsed tail (pack bytes)."""
    packets, i, n = [], 0, len(body)
    while i + 4 <= n:
        try:
            size = int(body[i:i + 4], 16)
        except ValueError:
            break  # raw pack bytes follow; the rest is not pkt-lines
        if size == 0:
            packets.append(("flush", None))
            i += 4
            continue
        if size == 1:
            packets.append(("delim", None))
            i += 4
            continue
        if size < 4 or i + size > n:
            break
        packets.append(("data", body[i + 4:i + size]))
        i += size
    return packets, body[i:]


# ---------------------------------------------------------------- git objects
def hash_object(otype, data):
    head = ("%s %d\0" % (otype, len(data))).encode()
    return hashlib.sha1(head + data).hexdigest()


def build_tree(entries):
    """entries: list of (mode, name, oid); returns the tree object bytes.
    Sorted git-style: entries ordered by name with directories as name+'/'."""
    def key(e):
        return e[1] + ("/" if e[0] == "40000" else "")
    out = bytearray()
    for mode, name, oid in sorted(entries, key=key):
        out += ("%s %s\0" % (mode, name)).encode() + bytes.fromhex(oid)
    return bytes(out)


def parse_tree(data):
    entries, i = [], 0
    while i < len(data):
        sp = data.index(b" ", i)
        mode = data[i:sp].decode()
        nul = data.index(b"\0", sp)
        name = data[sp + 1:nul].decode()
        oid = data[nul + 1:nul + 21].hex()
        entries.append((mode, name, oid))
        i = nul + 21
    return entries


def build_commit(tree, parents, message, author, committer, timestamp):
    def ident(who):
        return "%s %d +0000" % (who, timestamp)
    lines = ["tree %s" % tree]
    for p in parents:
        lines.append("parent %s" % p)
    lines.append("author " + ident(author))
    lines.append("committer " + ident(committer))
    lines.append("")
    lines.append(message if message.endswith("\n") else message + "\n")
    return "\n".join(lines).encode()


def parse_commit(data):
    text = data.decode("utf-8", "replace")
    head, _, message = text.partition("\n\n")
    tree, parents = None, []
    for line in head.split("\n"):
        if line.startswith("tree "):
            tree = line[5:].strip()
        elif line.startswith("parent "):
            parents.append(line[7:].strip())
    return {"tree": tree, "parents": parents, "message": message}


def build_tag(obj, otype, tag, tagger, message, timestamp):
    lines = ["object %s" % obj, "type %s" % otype, "tag %s" % tag,
             "tagger %s %d +0000" % (tagger, timestamp), "",
             message if message.endswith("\n") else message + "\n"]
    return "\n".join(lines).encode()


def parse_tag(data):
    text = data.decode("utf-8", "replace")
    head, _, message = text.partition("\n\n")
    out = {"message": message}
    for line in head.split("\n"):
        if line.startswith("object "):
            out["object"] = line[7:].strip()
        elif line.startswith("type "):
            out["type"] = line[5:].strip()
        elif line.startswith("tag "):
            out["tag"] = line[4:].strip()
        elif line.startswith("tagger "):
            out["tagger"] = line[7:].strip()
    return out

# ---------------------------------------------------------------- packfiles
def _varint_size(n):
    """Pack object header: type + size as varint (MSB continuation)."""
    out = bytearray()
    b = (n & 0x0F)
    n >>= 4
    while n:
        out.append(b | 0x80)
        b = n & 0x7F
        n >>= 7
    out.append(b)
    return bytes(out)


def write_pack(objects):
    """objects: list of (oid, otype, data) — plain, no deltas. Returns bytes."""
    body = bytearray()
    body += b"PACK" + (2).to_bytes(4, "big") + len(objects).to_bytes(4, "big")
    type_no = {"commit": 1, "tree": 2, "blob": 3, "tag": 4}
    for oid, otype, data in objects:
        head = _varint_size(len(data))
        first = head[0] | (type_no[otype] << 4)
        body += bytes([first]) + head[1:] + zlib.compress(data)
    trailer = hashlib.sha1(bytes(body)).digest()
    return bytes(body) + trailer


def _read_varint(buf, i):
    """Read a pack size varint; returns (size, next_index)."""
    size = buf[i] & 0x0F
    shift = 4
    i += 1
    while buf[i - 1] & 0x80:
        size |= (buf[i] & 0x7F) << shift
        shift += 7
        i += 1
    return size, i


def read_pack(pack, resolve_base=None):
    """Parse a pack (v2/v3, plain + OFS/REF deltas). Returns list of
    (oid, otype, data) in pack order. resolve_base(oid) -> (otype, data)
    for thin-pack bases the client already holds."""
    if len(pack) < 12 or pack[:4] != b"PACK":
        raise ValueError("not a packfile")
    count = int.from_bytes(pack[8:12], "big")
    i = 12
    objs = []          # (oid, otype, data) in order
    by_offset = {}     # offset -> (oid, otype, data)
    type_name = {1: "commit", 2: "tree", 3: "blob", 4: "tag"}
    for _ in range(count):
        start = i
        c = pack[i]
        otype_no = (c >> 4) & 7
        size, i = _read_varint(pack, i)
        if otype_no in (1, 2, 3, 4):
            d = zlib.decompressobj()
            data = d.decompress(pack[i:])
            i += len(pack[i:]) - len(d.unused_data)
            otype = type_name[otype_no]
        elif otype_no == 6:  # OFS_DELTA
            b = pack[i]
            i += 1
            off = b & 0x7F
            while b & 0x80:
                b = pack[i]
                i += 1
                off = ((off + 1) << 7) | (b & 0x7F)
            base_off = start - off
            d = zlib.decompressobj()
            delta = d.decompress(pack[i:])
            i += len(pack[i:]) - len(d.unused_data)
            base = by_offset.get(base_off)
            if base is None:
                raise ValueError("ofs-delta base missing")
            otype, data = base[1], _apply_delta(base[2], delta)
        elif otype_no == 7:  # REF_DELTA
            base_oid = pack[i:i + 20].hex()
            i += 20
            d = zlib.decompressobj()
            delta = d.decompress(pack[i:])
            i += len(pack[i:]) - len(d.unused_data)
            base = None
            for o in objs:
                if o[0] == base_oid:
                    base = o
                    break
            if base is None and resolve_base is not None:
                got = resolve_base(base_oid)
                if got is not None:
                    base = (base_oid, got[0], got[1])
            if base is None:
                raise ValueError("ref-delta base missing")
            otype, data = base[1], _apply_delta(base[2], delta)
        else:
            raise ValueError("unknown pack object type %d" % otype_no)
        oid = hash_object(otype, data)
        objs.append((oid, otype, data))
        by_offset[start] = (oid, otype, data)
    return objs


def _apply_delta(base, delta):
    """Apply a git delta to base bytes."""
    def varint(buf, i):
        v = 0
        shift = 0
        while True:
            b = buf[i]
            i += 1
            v |= (b & 0x7F) << shift
            shift += 7
            if not (b & 0x80):
                return v, i
    src_size, i = varint(delta, 0)
    if src_size != len(base):
        raise ValueError("delta source size mismatch")
    tgt_size, i = varint(delta, i)
    out = bytearray()
    while i < len(delta):
        op = delta[i]
        i += 1
        if op & 0x80:  # copy from base
            off = size = 0
            for k in range(4):
                if op & (1 << k):
                    off |= delta[i] << (8 * k)
                    i += 1
            for k in range(3):
                if op & (0x10 << k):
                    size |= delta[i] << (8 * k)
                    i += 1
            if size == 0:
                size = 0x10000
            out += base[off:off + size]
        elif op:  # insert literal
            out += delta[i:i + op]
            i += op
        else:
            raise ValueError("delta opcode 0")
    if len(out) != tgt_size:
        raise ValueError("delta target size mismatch")
    return bytes(out)


# ---------------------------------------------------------------- object store
class ObjectStore:
    def __init__(self):
        self.objs = {}   # oid -> (otype, data)
        self._commit_meta = {}  # oid -> (tree_oid, [parent oids])

    def put(self, otype, data):
        oid = hash_object(otype, data)
        if oid not in self.objs:
            self.objs[oid] = (otype, data)
            if otype == "commit":
                c = parse_commit(data)
                self._commit_meta[oid] = (c["tree"], c["parents"])
        return oid

    def commit_meta(self, oid):
        """(tree_oid, parents) for a commit, from cache or by parsing."""
        meta = self._commit_meta.get(oid)
        if meta is not None:
            return meta
        got = self.objs.get(oid)
        if got is None or got[0] != "commit":
            return None
        c = parse_commit(got[1])
        meta = (c["tree"], c["parents"])
        self._commit_meta[oid] = meta
        return meta

    def get(self, oid):
        return self.objs.get(oid)

    def has(self, oid):
        return oid in self.objs

    def reachable(self, tips, stop=None):
        """All oids reachable from tips (commits, tags, trees, blobs),
        following parents, trees and tag targets. stop: set of oids whose
        subtrees are NOT followed (have-exclusion)."""
        stop = stop or set()
        seen, stack = set(), list(tips)
        while stack:
            oid = stack.pop()
            if oid in seen or oid in stop or oid == ZERO_OID:
                continue
            got = self.objs.get(oid)
            if got is None:
                continue
            seen.add(oid)
            otype, data = got
            if otype == "commit":
                tree, parents = self.commit_meta(oid)
                stack.append(tree)
                stack.extend(parents)
            elif otype == "tree":
                for _m, _n, child in parse_tree(data):
                    stack.append(child)
            elif otype == "tag":
                stack.append(parse_tag(data)["object"])
        return seen

    def is_ancestor(self, anc, desc):
        """True if anc is desc or an ancestor commit of desc."""
        if anc == desc:
            return True
        seen, stack = set(), [desc]
        while stack:
            oid = stack.pop()
            if oid in seen or oid == ZERO_OID:
                continue
            seen.add(oid)
            meta = self.commit_meta(oid)
            if meta is None:
                continue
            stack.extend(meta[1])
        return anc in seen

    def commit_chain(self, tip):
        """Commits reachable from tip, newest-first by creation order."""
        order, seen, stack = [], set(), [tip]
        while stack:
            oid = stack.pop()
            if oid in seen or oid == ZERO_OID:
                continue
            meta = self.commit_meta(oid)
            if meta is None:
                continue
            seen.add(oid)
            order.append(oid)
            stack.extend(meta[1])
        order.reverse()
        return order

# ---------------------------------------------------------------- tree <-> files
def tree_files(store, tree_oid):
    """Flatten a tree oid to {path: (blob_oid, mode)} (recursive)."""
    out = {}

    def walk(tid, prefix):
        got = store.get(tid)
        if got is None or got[0] != "tree":
            return
        for mode, name, oid in parse_tree(got[1]):
            path = prefix + name
            if mode == "40000":
                walk(oid, path + "/")
            else:
                out[path] = (oid, mode)
    walk(tree_oid, "")
    return out


def build_tree_from_files(store, files):
    """files: {path: (blob_oid, mode)} -> root tree oid (creates trees)."""
    root = {}

    def insert(node, parts, oid, mode):
        if len(parts) == 1:
            node[parts[0]] = ("file", oid, mode)
            return
        child = node.get(parts[0])
        if child is None or child[0] != "dir":
            child = ("dir", {})
            node[parts[0]] = child
        insert(child[1], parts[1:], oid, mode)

    for path, (oid, mode) in files.items():
        insert(root, path.split("/"), oid, mode)

    def emit(node):
        entries = []
        for name, val in node.items():
            if val[0] == "file":
                entries.append((val[2], name, val[1]))
            else:
                entries.append(("40000", name, emit(val[1])))
        return store.put("tree", build_tree(entries))
    return emit(root)


def diff_files(store, old, new):
    """old/new: {path: (oid, mode)}. Returns list of
    (path, status, additions, deletions) with status in added/modified/
    changed; additions/deletions are line counts via difflib."""
    def blob_bytes(oid):
        got = store.get(oid)
        return got[1] if got is not None else b""

    out = []
    for path in sorted(set(old) | set(new)):
        if path not in old:
            data = blob_bytes(new[path][0])
            adds = data.count(b"\n") + (1 if data and not data.endswith(b"\n") else 0)
            out.append((path, "added", adds, 0))
        elif path not in new:
            out.append((path, "changed", 0, 1))
        elif old[path][0] != new[path][0]:
            a = blob_bytes(old[path][0]).decode("utf-8", "replace").splitlines()
            b = blob_bytes(new[path][0]).decode("utf-8", "replace").splitlines()
            sm = difflib.SequenceMatcher(a=a, b=b, autojunk=False)
            adds = dels = 0
            for tag, i1, i2, j1, j2 in sm.get_opcodes():
                if tag in ("insert", "replace"):
                    adds += j2 - j1
                if tag in ("delete", "replace"):
                    dels += i2 - i1
            out.append((path, "modified", adds, dels))
    return out


STORE_BLOB_CACHE = {}  # oid -> blob bytes (filled by Store.put_blob)


# ---------------------------------------------------------------- the store
class Repo:
    def __init__(self, dbid, owner, name, private, description):
        self.dbid = dbid
        self.owner = owner
        self.name = name
        self.private = private
        self.description = description or ""
        self.default_branch = "main"
        self.refs = {}        # refname -> oid
        self.labels = {}      # name -> color
        self.issues = {}      # number -> dict
        self.pulls = {}       # number -> dict
        self.comments = {}    # issue number -> list of {id, body}
        self.next_issue = 1
        self.next_comment = 1

    def path(self):
        return "/%s/%s" % (self.owner, self.name)


class Store:
    def __init__(self):
        self.objects = ObjectStore()
        self.repos = {}       # (owner, name) -> Repo
        self.next_dbid = 5000
        self.commit_seq = 0
        self.base_ts = int(os.environ.get("MAKEFUN_TRIAL_NOW", "1700000000"))
        self.lock = threading.RLock()

    def next_ts(self):
        self.commit_seq += 1
        return self.base_ts + self.commit_seq

    def iso(self, ts):
        return datetime.fromtimestamp(ts, tz=timezone.utc).strftime("%Y-%m-%dT%H:%M:%SZ")

    def put_blob(self, data):
        oid = self.objects.put("blob", data)
        STORE_BLOB_CACHE[oid] = data
        return oid

    def create_repo(self, owner, name, private, description):
        if (owner, name) in self.repos:
            return None
        repo = Repo(self.next_dbid, owner, name, private, description)
        self.next_dbid += 1
        self.repos[(owner, name)] = repo
        return repo

    def get_repo(self, owner, name):
        return self.repos.get((owner, name))

    def list_repos(self, owner):
        return [r for (o, _n), r in self.repos.items() if o == owner]

    def delete_repo(self, owner, name):
        return self.repos.pop((owner, name), None)

    def commit_files(self, repo, files, message, parents):
        """files: {path: bytes}. Creates blob/tree/commit objects; returns
        the commit oid. parents: list of commit oids."""
        tree_map = {}
        if parents:
            tip = self.objects.get(parents[0])
            if tip is not None and tip[0] == "commit":
                tree_map = tree_files(self.objects, parse_commit(tip[1])["tree"])
        for path, data in files.items():
            tree_map[path] = (self.put_blob(data), "100644")
        tree_oid = build_tree_from_files(self.objects, tree_map)
        ts = self.next_ts()
        author = "%s <%s>" % (VIEWER_NAME, VIEWER_EMAIL)
        data = build_commit(tree_oid, parents, message, author, author, ts)
        return self.objects.put("commit", data), ts

    def head_commit(self, repo, branch=None):
        ref = "refs/heads/" + (branch or repo.default_branch)
        return repo.refs.get(ref)

    def resolve_ref(self, repo, ref):
        """Resolve a branch name, full ref, or oid to a commit oid."""
        if ref in repo.refs:
            return repo.refs[ref]
        short = "refs/heads/" + ref
        if short in repo.refs:
            return repo.refs[short]
        if self.objects.get(ref) is not None:
            return ref
        return None

    def create_issue(self, repo, title, body, labels):
        for name in labels:
            if name not in repo.labels:
                return None, "unknown label %s" % name
        n = repo.next_issue
        repo.next_issue += 1
        ts = self.next_ts()
        issue = {"number": n, "title": title, "body": body or "",
                 "state": "open", "labels": [{"name": l} for l in labels],
                 "created_at": self.iso(ts), "updated_at": self.iso(ts),
                 "id": _b64("Issue:%d:%d" % (repo.dbid, n))}
        repo.issues[n] = issue
        repo.comments[n] = []
        return issue, None

    def create_pull(self, repo, title, head, base, body=""):
        head_oid = self.resolve_ref(repo, head)
        base_oid = self.resolve_ref(repo, base)
        if head_oid is None or base_oid is None:
            return None, "unknown head or base"
        n = repo.next_issue
        repo.next_issue += 1
        ts = self.next_ts()
        pr = {"number": n, "title": title, "body": body, "state": "open",
              "head_ref": head, "head_sha": head_oid,
              "base_ref": base, "base_sha": base_oid,
              "merged": False, "merged_at": None, "merge_commit_sha": None,
              "created_at": self.iso(ts), "updated_at": self.iso(ts),
              "id": _b64("PullRequest:%d:%d" % (repo.dbid, n))}
        repo.pulls[n] = pr
        return pr, None

    def merge_base(self, repo, a, b):
        """Newest common ancestor commit of a and b (or None)."""
        anc_a = set(self.objects.commit_chain(a))
        for oid in reversed(self.objects.commit_chain(b)):
            if oid in anc_a:
                return oid
        return None

    def three_way_merge(self, repo, pr):
        """Returns (merged_tree_map, conflict_paths) for pr, against the
        CURRENT tip of the base branch (not the sha captured at creation)."""
        cur_tip = repo.refs.get("refs/heads/" + pr["base_ref"])
        if cur_tip is None:
            return None, ["no base branch"]
        base_oid = self.merge_base(repo, pr["head_sha"], cur_tip)
        if base_oid is None:
            return None, ["<no merge base>"]
        base_tree = tree_files(self.objects, parse_commit(self.objects.get(base_oid)[1])["tree"])
        head_tree = tree_files(self.objects, parse_commit(self.objects.get(pr["head_sha"])[1])["tree"])
        cur_tree = tree_files(self.objects, parse_commit(self.objects.get(cur_tip)[1])["tree"])
        merged, conflicts = {}, []
        for path in sorted(set(base_tree) | set(head_tree) | set(cur_tree)):
            bv = base_tree.get(path)
            hv = head_tree.get(path)
            cv = cur_tree.get(path)
            if hv == bv:
                if cv is not None:
                    merged[path] = cv
            elif cv == bv:
                if hv is not None:
                    merged[path] = hv
            elif hv == cv:
                if hv is not None:
                    merged[path] = hv
            else:
                conflicts.append(path)
        return merged, conflicts

    def merge_pull(self, repo, pr):
        if pr["state"] != "open":
            return None, 405, "Pull request is already closed"
        merged, conflicts = self.three_way_merge(repo, pr)
        if merged is None:
            return None, 405, "No merge base"
        if conflicts:
            return None, 405, "Merge conflict in %s" % ", ".join(conflicts)
        tree_oid = build_tree_from_files(self.objects, merged)
        ts = self.next_ts()
        author = "%s <%s>" % (VIEWER_NAME, VIEWER_EMAIL)
        msg = "Merge pull request #%d from %s\n\n%s\n" % (pr["number"], pr["head_ref"], pr["title"])
        cur_tip = repo.refs.get("refs/heads/" + pr["base_ref"])
        data = build_commit(tree_oid, [cur_tip], msg, author, author, ts)
        sha = self.objects.put("commit", data)
        repo.refs["refs/heads/" + pr["base_ref"]] = sha
        pr["state"] = "closed"
        pr["merged"] = True
        pr["merged_at"] = self.iso(ts)
        pr["merge_commit_sha"] = sha
        pr["updated_at"] = self.iso(ts)
        return sha, 200, None


def _b64(text):
    return base64.urlsafe_b64encode(text.encode()).decode().rstrip("=")


def _unb64(text):
    try:
        pad = "=" * (-len(text) % 4)
        return base64.urlsafe_b64decode(text + pad).decode()
    except Exception:
        return None


