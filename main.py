def _pr_mergeable(p, _a):
    """GraphQL mergeable is an enum: MERGEABLE / CONFLICTING / UNKNOWN."""
    pr = p["pr"]
    if pr["state"] != "open":
        return "UNKNOWN"
    merged, conflicts = STORE.three_way_merge(p["repo"], pr)
    if merged is None:
        return "UNKNOWN"
    return "CONFLICTING" if conflicts else "MERGEABLE"


