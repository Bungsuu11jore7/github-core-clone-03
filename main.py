def _resolve_selection(parent, ptype, selection, variables, errors, fragments):
    out = {}
    for sel in selection:
        if "fragment" in sel:
            if sel["fragment"] == "inline":
                if sel["type"] is None or sel["type"] == ptype:
                    sub = _resolve_selection(parent, ptype, sel["selection"],
                                             variables, errors, fragments)
                    out.update(sub)
            else:
                frag = fragments.get(sel["fragment"])
                if frag is not None:
                    sub = _resolve_selection(parent, ptype, frag["selection"],
                                             variables, errors, fragments)
                    out.update(sub)
            continue
        field = sel["field"]
        alias = sel["alias"]
        if field == "__typename":
            out[alias] = ptype
            continue
        table = FIELD_TABLES.get(ptype, {})
        resolver = table.get(field)
        if resolver is None:
            errors.append({"message": 'Cannot query field "%s" on type "%s".' % (field, ptype)})
            out[alias] = None
            continue
        args = {k: _resolve_value(v, variables) for k, v in sel["args"].items()}
        try:
            value = resolver(parent, args)
        except GqlError as exc:
            errors.append({"message": str(exc)})
            out[alias] = None
            continue
        except Exception as exc:
            errors.append({"message": "field %s failed: %s" % (field, exc)})
            out[alias] = None
            continue
        if sel["selection"] is None:
            out[alias] = value
        elif value is None:
            out[alias] = None
        elif isinstance(value, list):
            out[alias] = [_resolve_selection(it, it["__type"], sel["selection"],
                                             variables, errors, fragments)
                          if isinstance(it, dict) and "__type" in it else it
                          for it in value]
        elif isinstance(value, dict) and "__type" in value:
            out[alias] = _resolve_selection(value, value["__type"], sel["selection"],
                                            variables, errors, fragments)
        else:
            out[alias] = value
    return out


def gql_execute(doc_text, variables):
    try:
        defs = _GqlParser(doc_text).parse_document()
    except Exception as exc:
        return {"data": None, "errors": [{"message": "parse error: %s" % exc}]}
    errors = []
    fragments = {d["name"]: d for d in defs if d["kind"] == "fragment"}
    ops = [d for d in defs if d["kind"] == "operation"]
    if not ops:
        return {"data": None, "errors": [{"message": "no operation in document"}]}
    op = ops[0]
    root_type = "Mutation" if op["op"] == "mutation" else "Query"
    data = _resolve_selection({"__type": root_type}, root_type, op["selection"],
                              variables or {}, errors, fragments)
    out = {"data": data}
    if errors:
        out["errors"] = errors
    return out

