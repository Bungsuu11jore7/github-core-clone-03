def _ref_entries(repo):
    """Sorted [(oid, refname)] for all refs, plus the HEAD pseudo-entry."""
    out = sorted(((oid, name) for name, oid in repo.refs.items()),
                 key=lambda e: e[1])
    head_oid = repo.refs.get("refs/heads/" + repo.default_branch, ZERO_OID)
    return head_oid, out


def _peel(store, oid):
    got = store.get(oid)
    if got is None:
        return None
    if got[0] == "tag":
        return parse_tag(got[1])["object"]
    return None


def git_advertisement(store, repo, service, proto2):
    """info/refs body for git-upload-pack / git-receive-pack."""
    if proto2:
        if service == "git-upload-pack":
            lines = [b"version 2\n"]
            for k, v in V2_CAPS:
                lines.append(("%s=%s\n" % (k, v)).encode())
            lines.append(FLUSH)
            return b"".join(pkt(l) for l in lines[:-1]) + FLUSH
        # receive-pack has no v2 advertisement; answer v0-style refs
        head_oid, refs = _ref_entries(repo)
        body = [pkt(b"# service=git-receive-pack\n"), FLUSH]
        if not refs:
            body.append(pkt(("%s capabilities^{}\0%s\n" % (ZERO_OID, V0_CAPS)).encode()))
        else:
            first = True
            for oid, name in refs:
                if first:
                    body.append(pkt(("%s %s\0%s\n" % (oid, name, V0_CAPS)).encode()))
                    first = False
                else:
                    body.append(pkt(("%s %s\n" % (oid, name)).encode()))
        body.append(FLUSH)
        return b"".join(body)
    # v0 advertisement
    head_oid, refs = _ref_entries(repo)
    body = [pkt(("# service=%s\n" % service).encode()), FLUSH]
    if service == "git-upload-pack":
        if not refs:
            body.append(pkt(("%s capabilities^{}\0%s\n" % (ZERO_OID, V0_CAPS)).encode()))
        else:
            body.append(pkt(("%s HEAD\0%s\n" % (head_oid, V0_CAPS)).encode()))
            for oid, name in refs:
                body.append(pkt(("%s %s\n" % (oid, name)).encode()))
                peeled = _peel(store, oid)
                if peeled:
                    body.append(pkt(("%s %s^{}\n" % (peeled, name)).encode()))
    else:
        if not refs:
            body.append(pkt(("%s capabilities^{}\0%s\n" % (ZERO_OID, V0_CAPS)).encode()))
        else:
            first = True
            for oid, name in refs:
                if first:
                    body.append(pkt(("%s %s\0%s\n" % (oid, name, V0_CAPS)).encode()))
                    first = False
                else:
                    body.append(pkt(("%s %s\n" % (oid, name)).encode()))
    body.append(FLUSH)
    return b"".join(body)


def git_ls_refs(store, repo, body):
    """v2 ls-refs. Returns the response bytes."""
    packets, _ = pkt_lines(body)
    peel = symrefs = unborn = False
    prefixes = []
    for kind, payload in packets:
        if kind != "data":
            continue
        line = payload.decode("utf-8", "replace").strip()
        if line == "peel":
            peel = True
        elif line == "symrefs":
            symrefs = True
        elif line == "unborn":
            unborn = True
        elif line.startswith("ref-prefix "):
            prefixes.append(line[11:])
    head_oid, refs = _ref_entries(repo)
    out = []

    def keep(name):
        return not prefixes or any(name.startswith(p) for p in prefixes)

    if keep("HEAD"):
        if head_oid == ZERO_OID:
            if unborn:
                line = "unborn HEAD"
                if symrefs:
                    line += " symref-target:refs/heads/" + repo.default_branch
                out.append(line + "\n")
        else:
            line = head_oid + " HEAD"
            if symrefs:
                line += " symref-target:refs/heads/" + repo.default_branch
            out.append(line + "\n")
    for oid, name in refs:
        if not keep(name):
            continue
        line = oid + " " + name
        if peel:
            peeled = _peel(store, oid)
            if peeled:
                line += " peeled:" + peeled
        out.append(line + "\n")
    return b"".join(pkt(l.encode()) for l in out) + FLUSH


def _fetch_send_set(store, wants, haves, depth, old_shallow):
    """Compute (send_oids, shallow, unshallow) for a fetch."""
    def tree_closure(tree_oid):
        seen, stack = set(), [tree_oid]
        while stack:
            oid = stack.pop()
            if oid in seen:
                continue
            got = store.get(oid)
            if got is None:
                continue
            seen.add(oid)
            if got[0] == "tree":
                for _m, _n, child in parse_tree(got[1]):
                    stack.append(child)
        return seen

    def held_for(have):
        """Objects the client already holds through this have. For a full
        fetch that is the have's whole history; for a depth fetch whose
        have is an old shallow boundary, only the have itself plus its
        tree/blobs (a deepen must re-deliver the parent)."""
        got = store.get(have)
        if got is None:
            return set()
        if depth is not None and have in old_shallow and got[0] == "commit":
            out = {have}
            out |= tree_closure(parse_commit(got[1])["tree"])
            return out
        return store.reachable([have])

    have_reach = set()
    for h in haves:
        have_reach |= held_for(h)
    send, shallow, unshallow = set(), [], []
    if depth is None:
        send = store.reachable(wants) - have_reach
        return send, [], []
    # depth-limited walk over commits
    included_commits = {}
    boundary = []
    queue = [(w, 0) for w in wants]
    seen_commit = set()
    while queue:
        oid, level = queue.pop(0)
        got = store.get(oid)
        if got is None:
            continue
        if got[0] == "tag":
            send.add(oid)
            target = parse_tag(got[1])["object"]
            queue.append((target, level))
            continue
        if got[0] != "commit":
            send.add(oid)
            continue
        if oid in seen_commit:
            continue
        seen_commit.add(oid)
        included_commits[oid] = level
        c = parse_commit(got[1])
        if level + 1 >= depth:
            boundary.append(oid)
        else:
            for p in c["parents"]:
                queue.append((p, level + 1))
    # closure of included commits: each commit + its tree/blobs only
    # (parents are NOT pulled in: that is the whole point of depth).
    for oid in included_commits:
        send.add(oid)
        c = parse_commit(store.get(oid)[1])
        send |= tree_closure(c["tree"])
    send -= have_reach
    # tags in the send set stay; non-commit wants included directly
    for w in wants:
        got = store.get(w)
        if got is not None and got[0] != "commit":
            send |= store.reachable([w])
    send -= have_reach
    # boundary = included commits whose parents were cut
    for oid in boundary:
        c = parse_commit(store.get(oid)[1])
        if any(p not in included_commits for p in c["parents"]):
            shallow.append(oid)
    for old in old_shallow:
        if old in included_commits:
            c = parse_commit(store.get(old)[1])
            if all(p in included_commits for p in c["parents"]):
                if old not in unshallow:
                    unshallow.append(old)
            elif old not in shallow:
                shallow.append(old)
        elif old not in shallow:
            shallow.append(old)
    return send, shallow, unshallow


def _sideband_pack(pack):
    out = bytearray()
    for i in range(0, len(pack), 65500):
        chunk = pack[i:i + 65500]
        out += pkt(bytes([1]) + chunk)
    return bytes(out)


def git_fetch_v2(store, repo, body):
    packets, _ = pkt_lines(body)
    wants, haves, old_shallow = [], [], []
    depth = None
    for kind, payload in packets:
        if kind != "data":
            continue
        line = payload.decode("utf-8", "replace").strip()
        if line.startswith("want "):
            wants.append(line[5:].split()[0])
        elif line.startswith("have "):
            haves.append(line[5:].split()[0])
        elif line.startswith("shallow "):
            old_shallow.append(line[8:].split()[0])
        elif line.startswith("deepen "):
            try:
                depth = int(line[7:])
            except ValueError:
                depth = None
    out = bytearray()
    out += pkt(b"acknowledgments\n")
    held = [h for h in haves if store.has(h)]
    if held:
        for h in held:
            out += pkt(("ACK %s\n" % h).encode())
        out += pkt(b"ready\n")
    else:
        out += pkt(b"NAK\n")
    out += DELIM
    cache_key = (id(repo), tuple(sorted(wants)), tuple(sorted(haves)),
                 depth, tuple(sorted(old_shallow)))
    cached = _pack_cache.get(cache_key)
    if cached is None:
        send, shallow, unshallow = _fetch_send_set(store, wants, haves, depth, old_shallow)
        objs = sorted(send)
        pack = write_pack([(oid, store.get(oid)[0], store.get(oid)[1]) for oid in objs]) if objs else None
        cached = (pack, shallow, unshallow)
        if len(_pack_cache) > 64:
            _pack_cache.clear()
        _pack_cache[cache_key] = cached
    pack, shallow, unshallow = cached
    if shallow or unshallow:
        out += pkt(b"shallow-info\n")
        for s in shallow:
            out += pkt(("shallow %s\n" % s).encode())
        for s in unshallow:
            out += pkt(("unshallow %s\n" % s).encode())
        out += DELIM
    if pack is not None:
        out += pkt(b"packfile\n")
        out += _sideband_pack(pack)
    out += FLUSH
    return bytes(out)


