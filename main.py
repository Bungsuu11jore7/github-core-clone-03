def _http_json(url, payload, timeout=10):
    data = json.dumps(payload).encode() if payload is not None else None
    req = urllib.request.Request(url, data=data,
                                 headers={"Content-Type": "application/json"},
                                 method="POST" if data is not None else "GET")
    with urllib.request.urlopen(req, timeout=timeout) as resp:
        return json.loads(resp.read().decode("utf-8"))


def main():
    env_url = os.environ.get("MAKEFUN_ENV_URL")
    if not env_url:
        sys.stderr.write("MAKEFUN_ENV_URL is not set\n")
        return 1
    server = Server(("127.0.0.1", 0), Handler)
    port = server.server_address[1]
    threading.Thread(target=server.serve_forever, daemon=True).start()
    base = env_url.rstrip("/")
    delay = 0.1
    for _ in range(60):
        try:
            _http_json(base + "/register", {"port": port}, timeout=5)
            break
        except Exception:
            time.sleep(delay)
            delay = min(delay * 1.5, 2.0)
    else:
        sys.stderr.write("register failed\n")
        return 1
    while True:
        try:
            done = _http_json(base + "/done", None, timeout=5)
            if done.get("done"):
                break
        except Exception:
            pass
        time.sleep(0.5)
    server.shutdown()
    return 0


if __name__ == "__main__":
    sys.exit(main())
