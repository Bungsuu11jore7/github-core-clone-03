def mcp_dispatch(raw, headers):
    """Returns (http_status, body_obj_or_None, extra_headers)."""
    try:
        req = json.loads(raw.decode("utf-8"))
    except Exception:
        return 400, {"jsonrpc": "2.0", "id": None,
                     "error": {"code": -32700, "message": "Parse error"}}, {}
    if not isinstance(req, dict):
        return 400, {"jsonrpc": "2.0", "id": None,
                     "error": {"code": -32600, "message": "Invalid Request"}}, {}
    method = req.get("method", "")
    rid = req.get("id")
    params = req.get("params") or {}

    def result(payload, extra=None):
        body = {"jsonrpc": "2.0", "id": rid, "result": payload}
        return 200, body, extra or {}

    def error(code, message):
        return 200, {"jsonrpc": "2.0", "id": rid,
                     "error": {"code": code, "message": message}}, {}

    if method == "server/discover":
        payload = {"supportedVersions": MCP_VERSIONS,
                   "capabilities": {"tools": {}},
                   "serverInfo": MCP_SERVER_INFO,
                   "_meta": {"io.modelcontextprotocol/serverInfo": MCP_SERVER_INFO}}
        return result(payload)
    if method == "initialize":
        want = (params.get("protocolVersion") or "")
        chosen = want if want in MCP_VERSIONS else "2025-11-25"
        payload = {"protocolVersion": chosen,
                   "capabilities": {"tools": {}},
                   "serverInfo": MCP_SERVER_INFO}
        return result(payload, {"Mcp-Session-Id": "session-1"})
    if method in ("notifications/initialized", "notifications/cancelled"):
        return 202, None, {}
    if method == "ping":
        return result({})
    if method == "tools/list":
        return result({"tools": MCP_TOOLS})
    if method == "tools/call":
        name = params.get("name", "")
        args = params.get("arguments") or {}
        known = {t["name"] for t in MCP_TOOLS}
        if name.split("__")[-1] not in known and name not in known:
            return error(-32602, "unknown tool %s" % name)
        obj, is_err, err_text = _mcp_call(name, args)
        if is_err:
            return result({"content": [{"type": "text",
                                        "text": _mcp_tool_text({"error": err_text})}],
                           "isError": True})
        return result({"content": [{"type": "text", "text": _mcp_tool_text(obj)}],
                       "structuredContent": obj})
    return error(-32601, "method not found: %s" % method)


